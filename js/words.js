function shuffleArray(items) {
  const arr = [...items];
  for (let i = arr.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export function getWordsForSession(stageId, mode) {
  const bank = WORD_BANKS[stageId] || WORD_BANKS.STAGE_1;
  // Pretest & Posttest MUST keep deterministic fixed order so all students face identical difficulty
  if (mode === 'PRETEST' || mode === 'POSTTEST' || stageId === 'PRETEST_A' || stageId === 'POSTTEST_A' || stageId === 'POSTTEST_B') {
    return [...bank];
  }
  return shuffleArray(bank);
}
